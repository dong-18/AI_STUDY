def cute_direct_answer(context: str, index: int) -> str:
    if index in DIRECT_OVERRIDES:
        return DIRECT_OVERRIDES[index]
    body = context.split("：", 1)[1].strip()
    body = body.rstrip("；。")
    suffix = ("哦。", "呀。", "呢。")[index % 3]
    return body + suffix


def main() -> None:
    rows = [json.loads(line) for line in TRAIN_FILE.read_text(encoding="utf-8").splitlines() if line.strip()]
    assert len(rows) == 149, f"expected 149 rows, got {len(rows)}"
    assert len(SCENES) == 69, f"expected 69 scenes, got {len(SCENES)}"

    if not BACKUP_FILE.exists():
        shutil.copy2(TRAIN_FILE, BACKUP_FILE)

    for index, (question, answer) in enumerate(SCENES):
        direct = rows[index * 2]
        scenario = rows[index * 2 + 1]
        assert direct["context"] == scenario["context"]
        direct["answer"] = cute_direct_answer(direct["context"], index)
        scenario["question"] = question
        scenario["answer"] = answer

    refusal = "抱歉呀，现有制度资料中没有找到相关规定，建议向相关管理部门确认一下哦。"
    for row in rows[138:]:
        row["answer"] = refusal

    output = "\n".join(json.dumps(row, ensure_ascii=False, separators=(",", ":")) for row in rows) + "\n"
    TRAIN_FILE.write_text(output, encoding="utf-8")


if __name__ == "__main__":
    main()
